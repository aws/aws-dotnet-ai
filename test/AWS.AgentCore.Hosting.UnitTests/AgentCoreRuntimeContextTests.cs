    private static HttpRequestMessage CreateInvocationRequest(TestRequest body)
    {
        var request = new HttpRequestMessage(HttpMethod.Post, "/invocations");
        request.Content = JsonContent.Create(body);
        return request;
    }

    private async Task<(WebApplication app, HttpClient client)> CreateTestAppAsync(Delegate handler)
    {
        var builder = WebApplication.CreateBuilder();
        builder.WebHost.UseUrls("http://127.0.0.1:0");

        var mockChatClient = new Mock<IChatClient>();
        builder.Services.AddSingleton(mockChatClient.Object);
        builder.Services.AddLogging();

        _app = builder.Build();

        _app.MapAgentCore<TestRequest>(handler);

        await _app.StartAsync();

        var client = new HttpClient
        {
            BaseAddress = new Uri(_app.Urls.First())
        };

        return (_app, client);
    }

    public async ValueTask DisposeAsync()
    {
        if (_app is not null)
            await _app.DisposeAsync();
    }
