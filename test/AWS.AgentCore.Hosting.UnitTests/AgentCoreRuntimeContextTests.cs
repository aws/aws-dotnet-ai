    [Fact]
    public async Task AllHeaders_ContainsAllRequestHeaders()
    {
        var ct = TestContext.Current.CancellationToken;
        AgentCoreRuntimeContext? captured = null;

        var (_, client) = await CreateTestAppAsync(
            async (TestRequest request, AgentCoreRuntimeContext context) =>
            {
                captured = context;
                return "ok";
            });

        var httpRequest = CreateInvocationRequest(new TestRequest("test"));
        httpRequest.Headers.Add("X-Amzn-Bedrock-AgentCore-Runtime-Session-Id", "sess-123");
        httpRequest.Headers.Add("X-Custom-Unrelated", "some-value");

        await client.SendAsync(httpRequest, ct);

        Assert.NotNull(captured);
        Assert.True(captured.AllHeaders.ContainsKey("X-Amzn-Bedrock-AgentCore-Runtime-Session-Id"));
        Assert.True(captured.AllHeaders.ContainsKey("X-Custom-Unrelated"));
        Assert.True(captured.AllHeaders.ContainsKey("Content-Type")); // set by JsonContent
    }

